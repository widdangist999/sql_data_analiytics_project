```sql
/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data using aggregate functions.
    - To analyze data distribution across different dimensions.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - Clauses: GROUP BY, ORDER BY
    - Joins: LEFT JOIN
===============================================================================
*/

-- 1. Find the total number of customers by country
SELECT
    country,
    COUNT(customer_key) AS total_customers
FROM gold_dim_customers
GROUP BY country
ORDER BY total_customers DESC;


-- 2. Find the total number of customers by gender
SELECT
    gender,
    COUNT(customer_key) AS total_customers
FROM gold_dim_customers
GROUP BY gender
ORDER BY total_customers DESC;


-- 3. Find the total number of products by category
SELECT
    category,
    COUNT(product_key) AS total_products
FROM gold_dim_products
GROUP BY category
ORDER BY total_products DESC;


-- 4. Find the average product cost by category
SELECT
    category,
    AVG(cost) AS avg_cost
FROM gold_dim_products
GROUP BY category
ORDER BY avg_cost DESC;


-- 5. Calculate total revenue by category
-- Starting from the fact table returns categories with matching sales records.
SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold_fact_sales AS f
LEFT JOIN gold_dim_products AS p
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;


-- 6. Calculate total revenue by category
-- Starting from the product dimension retains categories without matching sales.
SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold_dim_products AS p
LEFT JOIN gold_fact_sales AS f
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;


-- 7. Calculate total revenue generated by each customer
SELECT
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold_fact_sales AS f
LEFT JOIN gold_dim_customers AS c
    ON c.customer_key = f.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;


-- 8. Calculate the total quantity of items sold by customer country
SELECT
    c.country,
    SUM(f.quantity) AS total_sold_items
FROM gold_fact_sales AS f
LEFT JOIN gold_dim_customers AS c
    ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC;
```
